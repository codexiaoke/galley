export const SCENE_API_DOC = `**scene 里可以用的函数**

代码是普通的 JavaScript（不能用 import、网络、定时器），分两段：先把画面上的东西摆出来，再写若干步。每一步有两句话，**是两回事，不要写成一样的**：\`step("……")\` 的第一个参数是写给读者看的，显示在画面下面；\`say("……")\` 是讲的时候说的话，只在演示里当字幕和提词。舞台的宽高是 \`W\` 和 \`H\`（默认 800 × 450；ratio 是 4:3 时 800 × 600，1:1 时 600 × 600，21:9 时 800 × 340），坐标原点在左上角，**x、y 是东西的中心**。

摆东西（都返回一个"把手"，刚建出来是看不见的，要 show 才出现）：

| 函数 | 画出来是什么 |
|---|---|
| \`box(文字, { sub, w, h, tone })\` | 圆角方块。sub 是第二行小字；宽高不写时按文字自动定 |
| \`circle(文字, { r, tone })\` | 圆 |
| \`text(文字, { size, bold, mono, color, align })\` | 一行或几行文字（\\n 换行） |
| \`code(代码, { lines })\` | 一小段等宽的代码，最多 16 行；lines: [2, 3] 标出第 2、3 行 |
| \`frame(标题, { around: [a, b], pad })\` | 一圈虚线框，标题在左上角，表示边界（一个进程、一个沙箱、一台服务器）。around 给出它要围住的东西 |
| \`arrow(a, b, { label, bend, dashed, both })\` | 从 a 到 b 的箭头，跟着两端走。两端可以是东西，也可以是一个点 [x, y]。bend 是弯多少（正负决定往哪边弯）；both: true 两头都有箭头 |
| \`line(a, b, { label, bend, dashed })\` | 没有箭头的连线 |

位置：\`{ x, y }\` 直接给中心点；或者相对另一个东西：\`{ rightOf: a }\`、\`{ leftOf: a }\`、\`{ below: a }\`、\`{ above: a }\`，间距用 gap 调。不写位置时在舞台正中。几个东西一起排：\`row([a, b, c], { y, gap })\` 排成一行，\`column([a, b, c], { x, gap })\` 排成一列，\`grid([...], { cols })\` 排成网格，都整体居中。把手上可以读 \`a.x\`、\`a.y\`、\`a.w\`、\`a.h\`、\`a.left\`、\`a.right\`、\`a.top\`、\`a.bottom\`，用来算别的东西的位置。**优先用 row、column 和相对位置，少手算坐标。** 不用费心把东西摆满舞台：镜头会自动对准所有东西、放大到正好装下，摆得紧凑一点、相互关系清楚就行。

颜色只能用名字：\`ink\`（正文色）、\`soft\`、\`faint\`（更淡）、\`accent\`（强调色）、\`paper\`、\`raised\`、\`sunken\`、\`rule\`、\`code\`（底色类）、\`c1\` 到 \`c5\`（五种区分色）、\`none\`。名字后面加 \`/数字\` 是浓度，比如 \`"accent/15"\` 是很淡的强调色。最省事的是 \`tone\`：\`box("Worker", { tone: "c2" })\` 一次定下边框和淡底色。不能写 #ff0000 这种颜色，否则换主题、换深色模式时画面不会跟着变。

步骤：\`step("写给读者的一句话", () => { say("讲的时候说的话"); 动作…… })\`。

- 第一个参数是**文字**：一句完整的书面话，显示在画面下面，是文章正文的一部分。读者是自己看的，所以要简洁、准确，一眼读完。
- \`say("……")\` 是**讲稿**：讲这一步的时候嘴上说的话，演示里显示成字幕、出现在演讲者的提词里；文章页面上没有它，公开的幻灯片接口里也没有。它是口语，是在画面旁边对着人讲：可以先接上一步的话茬（"那换个地方跑呢？"），可以指着画面说（"看右边这个框"），可以把书面的那句拆成两三个短句、换成平常说话的词。**不要把第一个参数原样抄过来，也不要只改几个字**：写出来给人读的句子，念出来是生硬的。括号里要直接写一个字符串，不能用变量或拼接；一步只写一个。不打算拿去讲或者做视频的场景可以不写 say，这时字幕退回去用那句文字。

一步里的动作**默认一个接一个**；要同时发生的写进 \`together(() => { ... })\`；\`wait(毫秒)\` 停一下。写在第一个 step 之前的动作不是动画，而是一开始就有的样子（比如先 \`show(底图)\`）。

动作（每个都可以在最后加 \`{ dur, delay }\` 调时长和延后，单位毫秒）：

| 函数 | 作用 |
|---|---|
| \`show(a, b, ..., { from })\` | 出现。几个一起写时依次出现。from：rise 从下面浮上来（默认）、drop、left、right、pop 弹出来、fade 只淡入。箭头和连线是画出来的 |
| \`hide(a, b, ...)\` | 消失 |
| \`move(a, { x, y })\` / \`move([a, b], { dx, dy })\` | 挪到某个位置 / 挪动一段距离。连着它的箭头会跟着走 |
| \`set(a, { 属性: 值 })\` | 改属性并平滑过渡：w、h、r、opacity、scale、rotate、fill、stroke、color、tone、text、sub；代码块可以改 lines（标出哪几行）；连线可以改 label、bend |
| \`type(a, "新的文字")\` | 文字一个字一个字打出来 |
| \`highlight(a, b, ..., { tone })\` | 标出来：换成强调色并轻轻跳一下 |
| \`reset(a, b, ...)\` | 恢复成建出来时的颜色 |
| \`focus(a, b, ...)\` | 只看这几个，其余已经出现的都淡下去；\`focus()\` 不给参数是全部恢复 |
| \`dim(a, ...)\` / \`undim(a, ...)\` | 单独淡下去 / 恢复 |
| \`pulse(a, ...)\` | 轻轻跳一下，提醒读者看这里 |
| \`send(连线, { label, tone, reverse })\` | 一个小圆点沿着连线走过去，表示一条消息、一次请求。label 是它带着的字。reverse: true 是反着走。它走到了，下一个动作才开始 |
| \`zoomTo(a, b, ..., { pad })\` / \`zoomOut()\` | 镜头推近到这几个东西 / 回到全景（全景就是正好装下所有东西的那个镜头） |
| \`camera({ x, y, zoom })\` | 直接控制镜头。写在第一个 step 之前时，全景就按你摆的来，不再自动贴合 |

要点：
- 一个场景只讲一件事，四到八步最合适，最多 24 步；画面上的东西最多 80 个。
- 先 show 出主角，再一步步加东西；不要第一步就把所有东西都摆出来。讲到哪个，就 highlight 或 focus 哪个，读者的眼睛才知道看哪里。
- 文字和讲稿都说这一步发生了什么、为什么，不要写"现在显示方块 A"这种描述画面的话。文字是给人读的，讲稿是给人听的，两句的意思一致、说法不同。
- 方块里的字要短（两到六个字），细节放进 sub 或者讲解里。
- 代码出错时保存会失败，错误信息里有行号（从代码块的第一行算起）。`;
