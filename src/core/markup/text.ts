/**
 * 把正文源码还原成大致的显示文字：去掉引用标记的外壳、图片、链接的地址和 Markdown 的符号。
 * 用在搜索、摘录这些只关心"读者看到的字"的地方。不追求和页面逐字一致。
 */
export function plainText(source: string): string {
  return source
    .replace(/!\[[^\]]*\]\([^)]*\)/g, "") // 图片
    .replace(/^:{2,3}[a-z]*(\{[^}]*\})?\s*$/gim, "") // 单独成行的块级标记和它的结束行
    .replace(/:{1,3}[a-z]+\[/gi, "") // :cite[ 这样的开头
    .replace(/\]\{[^}]*\}/g, "") // ]{b=...}
    .replace(/:{1,3}[a-z]+\{[^}]*\}/gi, "") // :value{...}
    .replace(/\]\([^)]*\)/g, "") // 链接的地址
    .replace(/^\s*\|?\s*:?-{3,}:?\s*(\|\s*:?-{3,}:?\s*)*\|?\s*$/gm, "") // 表格的分隔行
    .replace(/[*_`#>[\]]/g, "")
    .replace(/\|/g, " ") // 表格的竖线换成空格，免得两格的字连在一起
    .replace(/[ \t]+/g, " ");
}
